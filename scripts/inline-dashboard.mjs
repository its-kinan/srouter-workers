// Build step: inline web-dist/index.html (the real SRouter React dashboard
// shell) into src/dashboard-html.ts so the Worker can serve it for `/` and
// SPA-fallback routes. The JS/CSS chunks are served as Workers Static Assets
// (see scripts/deploy.mjs); only this small shell is inlined.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { execSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const distDir = join(root, "web-dist");
const tarball = join(root, "web-dist.tar.gz");

// Extract the committed tarball if web-dist/ is missing (fresh clone).
if (!existsSync(join(distDir, "index.html"))) {
    if (!existsSync(tarball)) {
        throw new Error(
            "web-dist/index.html missing and web-dist.tar.gz not found. " +
            "Build the SRouter web app (apps/web) and re-create web-dist.tar.gz."
        );
    }
    mkdirSync(distDir, { recursive: true });
    execSync(`tar -xzf ${tarball} -C ${distDir} --no-same-owner`, { stdio: "inherit" });
}

const html = readFileSync(join(distDir, "index.html"), "utf8");
writeFileSync(
    join(root, "src", "dashboard-html.ts"),
    `// AUTO-GENERATED by scripts/inline-dashboard.mjs — do not edit.\n` +
    `// Real SRouter React dashboard shell (apps/web/dist/index.html).\n` +
    `export const DASHBOARD_HTML: string = ${JSON.stringify(html)};\n`
);
console.log(`inlined web-dist/index.html (${html.length} chars) -> src/dashboard-html.ts`);
