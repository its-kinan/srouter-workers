// Build step: inline public/index.html into src/dashboard-html.ts so the
// Worker serves the Phase 1 dashboard shell without the ASSETS binding.
// (Raw-API asset uploads default every file to application/octet-stream,
// which makes browsers download the page instead of rendering it.)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(join(root, "public", "index.html"), "utf8");
writeFileSync(
    join(root, "src", "dashboard-html.ts"),
    `// AUTO-GENERATED by scripts/inline-dashboard.mjs — do not edit.\nexport const DASHBOARD_HTML: string = ${JSON.stringify(html)};\n`
);
console.log(`inlined public/index.html (${html.length} chars) -> src/dashboard-html.ts`);
